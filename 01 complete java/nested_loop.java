public class nested_loop {
    public static void main(String[] args) {
        // nested loop = a loop inside another loop used otften with matrices or DSA
        for (int j = 1; j <= 3; j++){
            for (int i = 1; i <= 9; i++){
                System.out.print(i + " ");
            } 
            System.out.println();
        }
    }
}
